#!/usr/bin/env python3
"""Create AIR's original, quiet two-frequency cue; no downloaded sound assets."""

import argparse
import array
import hashlib
import math
import shutil
import struct
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "main/boards/custom/waveshare-air-monitor-1.8-v1/air_alert_tone.h"
SAMPLE_RATE = 16000
DURATION_SECONDS = 0.240


def synthesize():
    pcm = array.array("h")
    for index in range(round(SAMPLE_RATE * DURATION_SECONDS)):
        time = index / SAMPLE_RATE
        attack = min(1.0, time / 0.008)
        release = min(1.0, (DURATION_SECONDS - time) / 0.020)
        envelope = attack * release * math.exp(-time / 0.090)
        value = 0.18 * envelope * (0.72 * math.sin(2 * math.pi * 740 * time) +
                                   0.28 * math.sin(2 * math.pi * 1108 * time))
        pcm.append(round(32767 * value))
    if sys.byteorder != "little":
        pcm.byteswap()
    return pcm.tobytes()


def canonical_ogg(data):
    """Fix the random Ogg stream serial and refresh each page's checksum."""
    data = bytearray(data)
    offset = 0
    while offset < len(data):
        if data[offset:offset + 4] != b"OggS":
            raise ValueError("ffmpeg did not return complete Ogg pages")
        segment_count = data[offset + 26]
        page_size = 27 + segment_count + sum(data[offset + 27:offset + 27 + segment_count])
        if offset + page_size > len(data):
            raise ValueError("truncated Ogg page")
        struct.pack_into("<I", data, offset + 14, 0x41495234)
        data[offset + 22:offset + 26] = b"\0" * 4
        crc = 0
        for byte in data[offset:offset + page_size]:
            crc ^= byte << 24
            for _ in range(8):
                crc = ((crc << 1) ^ (0x04C11DB7 if crc & 0x80000000 else 0)) & 0xFFFFFFFF
        struct.pack_into("<I", data, offset + 22, crc)
        offset += page_size
    return bytes(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ffmpeg", default=shutil.which("ffmpeg"))
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--preview", type=Path, help="optional local Ogg listening copy")
    args = parser.parse_args()
    if not args.ffmpeg:
        parser.error("ffmpeg with libopus is required to regenerate the cue")
    pcm = synthesize()
    result = subprocess.run([args.ffmpeg, "-v", "error", "-fflags", "+bitexact",
                             "-f", "s16le", "-ar", str(SAMPLE_RATE), "-ac", "1", "-i", "pipe:0",
                             "-c:a", "libopus", "-b:a", "16000", "-vbr", "off",
                             "-frame_duration", "60", "-application", "audio",
                             "-flags:a", "+bitexact", "-map_metadata", "-1",
                             "-f", "ogg", "pipe:1"], input=pcm, capture_output=True, check=True)
    ogg = canonical_ogg(result.stdout)
    rows = ["    " + ", ".join(f"0x{byte:02x}" for byte in ogg[i:i + 12]) + ","
            for i in range(0, len(ogg), 12)]
    text = ("// Generated by scripts/generate_air_alert_tone.py; original synthesized audio.\n"
            f"// Ogg SHA256: {hashlib.sha256(ogg).hexdigest()}\n"
            "#pragma once\n\n#include <cstdint>\n\nnamespace air {\n\n"
            "inline constexpr uint8_t kAlertToneOgg[] = {\n" + "\n".join(rows) +
            "\n};\n\n}  // namespace air\n")
    args.output.write_text(text, encoding="utf-8")
    if args.preview:
        args.preview.write_bytes(ogg)
    samples = struct.unpack(f"<{len(pcm) // 2}h", pcm)
    rms = math.sqrt(sum((value / 32768) ** 2 for value in samples) / len(samples))
    print(f"{len(ogg)} Ogg bytes; source {DURATION_SECONDS * 1000:.0f} ms, "
          f"RMS {20 * math.log10(rms):.2f} dBFS, peak "
          f"{max(abs(value) for value in samples) / 32768:.4f}")


if __name__ == "__main__":
    main()
